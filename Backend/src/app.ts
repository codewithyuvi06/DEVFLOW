import express from 'express';
import cors from 'cors';
import helmet from 'helmet';
import cookieParser from 'cookie-parser';
import rateLimit from 'express-rate-limit';
import pinoHttp from 'pino-http';
import { env } from './config/env';
import authRoutes from './routes/authRoutes';
import teamRoutes from './routes/teamRoutes';
import projectRoutes from './routes/projectRoutes';
import issueRoutes from './routes/issueRoutes';
import dashboardRoutes from './routes/dashboardRoutes';
import activityRoutes from './routes/activityRoutes';
import notificationRoutes from './routes/notificationRoutes';
import repositoryRoutes from './routes/repositoryRoutes';
import { errorHandler, notFound } from './middleware/errorHandler';

export const app = express();
app.disable('x-powered-by');
app.set('trust proxy', env.NODE_ENV === 'production' ? 1 : false);
app.use(helmet());
app.use(cors({ origin: env.FRONTEND_URL, credentials: true, methods: ['GET','POST','PATCH','PUT','DELETE','OPTIONS'], allowedHeaders: ['Content-Type','Authorization'] }));
app.use(express.json({ limit: '1mb' })); app.use(express.urlencoded({ extended: false, limit: '1mb' })); app.use(cookieParser());
app.use(pinoHttp({ quietReqLogger: env.NODE_ENV === 'test' }));
app.get('/health', (_req, res) => res.json({ success: true, service: 'devflow-api', status: 'healthy', timestamp: new Date().toISOString() }));
const prefix = env.API_PREFIX;
app.use(`${prefix}/auth`, rateLimit({ windowMs: 15 * 60 * 1000, limit: 100, standardHeaders: 'draft-7', legacyHeaders: false }), authRoutes);
app.use(`${prefix}/teams`, teamRoutes); app.use(`${prefix}/projects`, projectRoutes); app.use(`${prefix}/issues`, issueRoutes);
app.use(`${prefix}/dashboard`, dashboardRoutes); app.use(`${prefix}/activity`, activityRoutes); app.use(`${prefix}/notifications`, notificationRoutes); app.use(`${prefix}`, repositoryRoutes);
app.use(notFound); app.use(errorHandler);
